BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

DO $guard$
BEGIN
  IF to_regclass('public.naval_asset_history') IS NOT NULL
     OR to_regclass('public.naval_position_history') IS NOT NULL THEN
    RAISE EXCEPTION 'Private naval history tables already exist; review schema first';
  END IF;
  IF to_regclass('public.events') IS NULL OR to_regclass('public.tracks') IS NULL THEN
    RAISE EXCEPTION 'Reviewed live tables are missing';
  END IF;
  IF (SELECT relrowsecurity FROM pg_class WHERE oid='public.events'::regclass)
     OR (SELECT relrowsecurity FROM pg_class WHERE oid='public.tracks'::regclass) THEN
    RAISE EXCEPTION 'Live table RLS differs from reviewed schema';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='events'
      AND policyname='public read events' AND cmd='SELECT' AND 'anon'=ANY(roles)
  ) THEN
    RAISE EXCEPTION 'Reviewed public events SELECT policy is missing';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables WHERE pubname='supabase_realtime'
      AND schemaname='public' AND tablename='events'
  ) OR NOT EXISTS (
    SELECT 1 FROM pg_publication_tables WHERE pubname='supabase_realtime'
      AND schemaname='public' AND tablename='tracks'
  ) THEN
    RAISE EXCEPTION 'Realtime publication differs from reviewed schema';
  END IF;
END $guard$;

CREATE TABLE public.naval_asset_history (
  asset_key text PRIMARY KEY,
  mmsi text,
  imo text,
  callsign text,
  vessel_name text,
  vessel_class text,
  operator text,
  country text,
  aliases jsonb NOT NULL DEFAULT '[]'::jsonb,
  first_seen_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL,
  lat double precision NOT NULL,
  lon double precision NOT NULL,
  speed_kts double precision,
  heading_deg double precision,
  source_name text NOT NULL,
  source_confidence integer,
  qualification_level text NOT NULL,
  qualification_reason text NOT NULL,
  search_text text NOT NULL DEFAULT ''
);
CREATE INDEX naval_asset_history_last_seen_idx ON public.naval_asset_history (last_seen_at DESC);
CREATE UNIQUE INDEX naval_asset_history_mmsi_idx ON public.naval_asset_history (mmsi) WHERE mmsi IS NOT NULL;
CREATE UNIQUE INDEX naval_asset_history_imo_idx ON public.naval_asset_history (imo) WHERE imo IS NOT NULL;
CREATE INDEX naval_asset_history_location_idx ON public.naval_asset_history (lat, lon);
CREATE FUNCTION public.stratops_preserve_naval_asset_freshness()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $function$
BEGIN
  NEW.first_seen_at := LEAST(OLD.first_seen_at, NEW.first_seen_at);
  NEW.imo := coalesce(NEW.imo, OLD.imo);
  SELECT coalesce(jsonb_agg(alias ORDER BY alias), '[]'::jsonb) INTO NEW.aliases
  FROM (SELECT DISTINCT alias FROM jsonb_array_elements_text(OLD.aliases || NEW.aliases)
        AS elements(alias)) AS unique_aliases;
  IF NEW.last_seen_at < OLD.last_seen_at THEN
    NEW.mmsi := OLD.mmsi;
    NEW.callsign := OLD.callsign;
    NEW.vessel_name := OLD.vessel_name;
    NEW.vessel_class := OLD.vessel_class;
    NEW.operator := OLD.operator;
    NEW.country := OLD.country;
    NEW.last_seen_at := OLD.last_seen_at;
    NEW.lat := OLD.lat;
    NEW.lon := OLD.lon;
    NEW.speed_kts := OLD.speed_kts;
    NEW.heading_deg := OLD.heading_deg;
    NEW.source_name := OLD.source_name;
    NEW.source_confidence := OLD.source_confidence;
    NEW.qualification_reason := OLD.qualification_reason;
  END IF;
  IF OLD.qualification_level = 'confirmed' THEN
    NEW.qualification_level := 'confirmed';
  END IF;
  NEW.search_text := lower(concat_ws(' ', NEW.mmsi, NEW.imo, NEW.callsign,
    NEW.vessel_name, NEW.aliases::text));
  RETURN NEW;
END;
$function$;
CREATE TRIGGER stratops_preserve_naval_asset_freshness
BEFORE UPDATE ON public.naval_asset_history FOR EACH ROW
EXECUTE FUNCTION public.stratops_preserve_naval_asset_freshness();
ALTER TABLE public.naval_asset_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.naval_asset_history FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.naval_asset_history TO service_role;

CREATE TABLE public.naval_position_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_key text NOT NULL REFERENCES public.naval_asset_history(asset_key),
  observed_at timestamptz NOT NULL,
  lat double precision NOT NULL,
  lon double precision NOT NULL,
  speed_kts double precision,
  heading_deg double precision,
  source_name text NOT NULL,
  source_confidence integer,
  CONSTRAINT naval_position_history_observation_unique UNIQUE (asset_key, observed_at, lat, lon)
);
CREATE INDEX naval_position_history_asset_time_idx ON public.naval_position_history (asset_key, observed_at DESC);
ALTER TABLE public.naval_position_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.naval_position_history FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.naval_position_history TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.naval_position_history_id_seq TO service_role;

-- The existing anon events policy remains permissive, so this restrictive policy
-- is necessary. The authenticated role gets its former read access explicitly.
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
CREATE POLICY stratops_events_authenticated_select ON public.events
  FOR SELECT TO authenticated USING (true);
CREATE POLICY stratops_events_naval_live_only ON public.events AS RESTRICTIVE
  FOR SELECT TO anon, authenticated USING (
    report_type IS DISTINCT FROM 'signal'
    OR (coalesce(source_key, '') NOT LIKE 'ais-%'
        AND coalesce(dedupe_key, '') NOT LIKE 'ais-%')
    OR occurred_at >= now() - interval '24 hours'
  );

ALTER TABLE public.tracks ENABLE ROW LEVEL SECURITY;
CREATE POLICY stratops_tracks_public_select ON public.tracks
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY stratops_tracks_naval_live_only ON public.tracks AS RESTRICTIVE
  FOR SELECT TO anon, authenticated USING (
    track_type IS DISTINCT FROM 'naval'
    OR occurred_at >= now() - interval '24 hours'
  );

-- Never add the private history tables to supabase_realtime.
COMMIT;
